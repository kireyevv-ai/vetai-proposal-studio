"""Эвристический поиск «подозрительных» фраз в тексте модели.

Это дополнительный (не блокирующий) контур проверки: ищем числовые цены,
обещания/обязательства и незаземлённые заявления о самом исполнителе (опыт,
заслуги, команда, сертификаты, рекламные клише), которые модель не должна была
придумывать (REQ-11, REQ-12). Найденное **не удаляется автоматически** — выводится
как предупреждение для ручной проверки (совместно с OQ-07).

Эвристика заведомо неполная и может давать ложные срабатывания — это лишь сигнал
для человека, а не доказательство галлюцинации. Основную защиту дают
программная подстановка коммерческих условий и политика заземления разделов.

Проверяются только текстовые разделы, созданные моделью; коммерческие разделы
формируются кодом из доверенных данных и в проверке не нуждаются.
"""

from __future__ import annotations

import re

_PRICE_RE = re.compile(
    r"\d[\d\s\u00a0.,]*\s*(?:₽|руб\w*|коп\w*)",
    re.IGNORECASE,
)
_PROMISE_RE = re.compile(
    r"(гарант\w*|SLA|штраф\w*|пен[иья]\w*|возврат\w*|компенсац\w*|"
    r"скидк\w*|обязуюсь|100\s*%|бесплатн\w*|пожизненн\w*)",
    re.IGNORECASE,
)
# Незаземлённые заявления исполнителя о себе и рекламные клише (Часть А, В).
_CLAIM_RE = re.compile(
    r"(\bведущ\w*|\bлидер\w*|\bкрупнейш\w*|\bлучш\w*|"
    r"опыт\w*|стаж\w*|лет\s+на\s+рынке|год\w*\s+на\s+рынке|"
    r"сертифик\w*|сертифиц\w*|аккредит\w*|награ\w*|"
    r"команд\w*|штат\w*|"
    r"репутац\w*|надёжн\w*|надежн\w*|"
    r"партн[её]р\w*|"
    r"индивидуальн\w*\s+подход\w*|широк\w*\s+спектр\w*|под\s+ключ|"
    r"техническ\w*\s+поддержк\w*|обучени\w*)",
    re.IGNORECASE,
)


def find_risky_fragments(text: str) -> list[str]:
    """Вернуть уникальные «подозрительные» фрагменты (цены/обещания/заявления)."""
    if not text:
        return []

    found: list[str] = []
    seen: set[str] = set()
    for pattern in (_PRICE_RE, _PROMISE_RE, _CLAIM_RE):
        for match in pattern.finditer(text):
            fragment = match.group(0).strip()
            key = fragment.casefold()
            if key and key not in seen:
                seen.add(key)
                found.append(fragment)
    return found
